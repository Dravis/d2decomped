"""Hit function 20, Lightning Fury (FUN_005ab370): the oracle for test_lightning_fury.

    uv run python hit_fury.py > ../../tests/hit_fury_cases.inc

FUN_005ab370 runs for real (ECX a game, EDX the missile: its class a Missiles.txt
row with pSrvHitFunc 20, the stack the unit it struck) with game.exe's tables
loaded (skill_tips.boot), and so do the area walk FUN_0056b7e0, its
callback FUN_005ab2a0 and the owner's lookup: FUN_00552fd0 (the missile's
+0xc8 bit 0x400, then FUN_00552f60 on its +0x94 type and +0x98 id, through
the game's unit hash at 0x6e10e0[type]). Hooked: the missile's skill
and level (FUN_0064a280: 35, Lightning Fury; FUN_0064a210: 1), the calc
(FUN_00646ca0, handed skill +0x64 aurarange or +0x138 calc1), the subtiles
(FUN_0045adf0 / FUN_0045ae20 the missile's, FUN_006488c0 / FUN_00648900 a
path's), the room and its one-room list (FUN_00620bb0, FUN_00619790), the
town test (FUN_0061ab00: not town), the room reach (FUN_0056b770: in reach),
the MonStats flag test (FUN_00457490: clear), the unit filter (FUN_0056b3e0:
logs its flag, takes the monsters) and the maker FUN_0059fa30.

The room holds, in its list order: the owner (a player, subtile 98, 200),
the unit the missile struck (101, 200), another monster (100, 203) and one
out of reach (110, 200); the missile is at (100, 200). The walk's rooms
(FUN_00620bb0) and the filter's caster (FUN_0056b3e0's ECX) are the owner's,
asserted on every case. Two more rows have no owner (bit 0x400 clear; set,
but the id finds no unit): FUN_005ab370 returns 1 and makes none.
"""
import skill_tips

ROOM_UNITS = ((0, 98, 200), (1, 101, 200), (1, 100, 203), (1, 110, 200))   # (unit type, subtile x, y)
OWNER_ID = 7                                    # the owner's unit id (+0xc), a player (type 0)


def main():
    e = skill_tips.boot()
    tables = e.r32(0x744304)
    records, count = e.r32(tables + 0xB64), e.r32(tables + 0xB6C)
    skills = e.r32(tables + 0xB98)
    fury = 35                                   # Skills.txt Id 35, Lightning Fury
    assert e.r16(skills + fury * 0x23C) == fury
    skill = skills + fury * 0x23C
    players = e.r32(0x6E10E0)                   # FUN_00552f60: type 0's hash heads at game + this
    game, missile, room, lists = e.alloc(players + 0x80 * 4), e.alloc(0x100), e.alloc(0x100), e.alloc(0x10)
    units = []
    for kind, x, y in ROOM_UNITS:
        unit, path = e.alloc(0x100), e.alloc(0x10)
        e.w32(unit, kind)
        e.w32(unit + 0x2C, path)
        e.w32(path, x)
        e.w32(path + 4, y)
        units.append(unit)
    for unit, after in zip(units, units[1:] + [0]):
        e.w32(unit + 0xE8, after)
    e.w32(room + 0x74, units[0])
    e.w32(lists, room)
    owner, struck = units[0], units[1]
    e.w32(owner + 0xC, OWNER_ID)
    e.w32(game + players + (OWNER_ID & 0x7F) * 4, owner)
    e.w32(missile + 0x94, 0)
    made, filters, calcs, callers = [], [], {}, set()

    def maker(h):
        params = h.mu.reg_read(skill_tips.emu.UC_X86_REG_EDX)
        made.append([h.r32(params + 4 * k) for k in range(0x17)])
        return 1

    def calc(h):
        assert h.arg(0) == owner and (h.arg(2), h.arg(3)) == (fury, 1)
        return calcs[h.arg(1)] & 0xFFFFFFFF

    def room_list(h):
        h.w32(h.arg(1), lists)
        h.w32(h.arg(2), 1)
        return 0

    def takes(h):
        filters.append(h.arg(0))
        callers.add(h.mu.reg_read(skill_tips.emu.UC_X86_REG_ECX))
        return int(h.r32(h.mu.reg_read(skill_tips.emu.UC_X86_REG_EDX)) == 1)

    e.hook(0x64A280, lambda h: fury, 1)
    e.hook(0x64A210, lambda h: 1, 1)
    e.hook(0x646CA0, calc, 4)
    e.hook(0x45ADF0, lambda h: 100, 0)
    e.hook(0x45AE20, lambda h: 200, 0)
    e.hook(0x6488C0, lambda h: h.r32(h.arg(0)), 1)
    e.hook(0x648900, lambda h: h.r32(h.arg(0) + 4), 1)
    def room_of(h):
        callers.add(h.arg(0))
        return room

    e.hook(0x620BB0, room_of, 1)
    e.hook(0x619790, room_list, 3)
    e.hook(0x61AB00, lambda h: 0, 1)
    e.hook(0x56B770, lambda h: 1, 0)
    e.hook(0x457490, lambda h: 0, 0)
    e.hook(0x56B3E0, takes, 1)
    e.hook(0x59FA30, maker, 0)
    e.w32(missile, 3)
    print("// Stock game.exe 1.14d, FUN_005ab370 -> FUN_0056b7e0 -> FUN_005ab2a0; generated by tools/emu/hit_fury.py.")
    print("// { row, sHitPar1, sHitPar2, aurafilter, aurarange, calc1, the walk's filter, missiles made, their x, y (flags 0x20, from the missile),")
    print("//   owned: 1 FUN_00552fd0 finds the owner, 0 the missile's +0xc8 bit 0x400 is clear, -1 set but its id finds no unit }")
    for row in range(count):
        record = records + row * 0x1A4
        if e.r16(record + 0xE) != 20:
            continue
        e.w32(missile + 4, row)
        for hit_par1 in (0, 4):
            for hit_par2 in (0, 1, 2, 3):
                for aura_filter in (0, 0xA583):
                    for aurarange, calc1 in ((-1, -1), (0, 0), (4, 2), (2, 5)):
                        e.w32(record + 0x4C, hit_par1)
                        e.w32(record + 0x50, hit_par2)
                        e.w32(skill + 0x50, aura_filter)
                        calcs.clear()
                        calcs[e.r32(skill + 0x64)] = aurarange
                        calcs[e.r32(skill + 0x138)] = calc1
                        made.clear()
                        filters.clear()
                        callers.clear()
                        e.w32(missile + 0xC8, 0x400)
                        e.w32(missile + 0x98, OWNER_ID)
                        assert e.call(0x5AB370, struck, ecx=game, edx=missile) == 3
                        assert len(set(filters)) <= 1 and callers == {owner}
                        spots = []
                        for field in made:
                            assert field[0] == 0x20 and field[1] == owner and field[2] == missile and field[4] == e.r16(record + 0x24)
                            spots += [field[7], field[8]]
                        spots += [-1] * (6 - len(spots))
                        print(f"    {{ {row}, {hit_par1}, {hit_par2}, {aura_filter:#x}, {aurarange}, {calc1}, {filters[0] if filters else 0:#x}, {len(made)}, {{ {', '.join(map(str, spots))} }}, 1 }},")
        for owned, flags, owner_id in ((0, 0, OWNER_ID), (-1, 0x400, OWNER_ID + 1)):
            e.w32(record + 0x4C, 4)
            e.w32(record + 0x50, 3)
            e.w32(skill + 0x50, 0)
            calcs.clear()
            made.clear()
            filters.clear()
            e.w32(missile + 0xC8, flags)
            e.w32(missile + 0x98, owner_id)
            assert e.call(0x5AB370, struck, ecx=game, edx=missile) == 1 and not filters
            print(f"    {{ {row}, 4, 3, 0x0, 0, 0, 0x0, {len(made)}, {{ -1, -1, -1, -1, -1, -1 }}, {owned} }},")


if __name__ == "__main__":
    main()
